  const uint8_t per = (uint8_t)((MAX_PACKET_PAYLOAD - 12) / OTA_HAVE_ROW_BYTES);
  const uint8_t total = (uint8_t)((255 + per - 1) / per);
  uint8_t sid[4] = {1, 2, 3, 4}, digest[4] = {5, 6, 7, 8};
